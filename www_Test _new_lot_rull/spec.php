<p>功能說明:</p>
<p>1. 分析依賴查詢</p>
<p>2. 分析依賴修改 ：</p>
<p>&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;主要功能是用來修改依賴的錯誤測試項目，讓檢驗員可以重新選擇檢驗項目‧</p>
<p>3. TM (Total Metal) 數據自動產生</p>
<p>&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;Total Metal 數值是由M13、M21、TT的各項檢驗數據加總而成‧數據無法在舊的Barcode 系統輸入，必須使用網頁版的才能夠輸入‧</p>
<p>&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;可由舊的Barcode3.66或由網頁版選擇TM檢驗項目，選擇TM檢驗項目時必須同時選擇M13、M21、TT‧單選TM將無法取得正確的檢驗數據‧</p>
<p>&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;當USER每次在網頁版輸入 TT 或 M13 或 M21 時都會自動更新TM的值‧如果檢驗當時的LOT有項目還沒完成，將會搜尋資料庫裏面相同客戶、同項產品最近的檢驗通過數值，</p>
<p>&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;以作為TM的相關組成部分，但是如果原LOT有檢驗過將以本身的LOT檢驗成果為依據‧</p>
